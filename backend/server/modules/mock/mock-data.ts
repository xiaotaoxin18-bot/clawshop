// ============ 工具函数 ============

let productIdCounter = 100;
let inboundIdCounter = 100;
let outboundIdCounter = 100;
let alertIdCounter = 100;
let warehouseIdCounter = 100;

export function generateProductId(): string {
  return `prod-${String(productIdCounter++).padStart(3, '0')}`;
}

export function generateInboundId(): string {
  return `in-${String(inboundIdCounter++).padStart(3, '0')}`;
}

export function generateOutboundId(): string {
  return `out-${String(outboundIdCounter++).padStart(3, '0')}`;
}

export function generateAlertId(): string {
  return `alert-${String(alertIdCounter++).padStart(3, '0')}`;
}

export function generateWarehouseId(): string {
  return `wh-${String(warehouseIdCounter++).padStart(3, '0')}`;
}

export function generateOrderNo(type: 'inbound' | 'outbound'): string {
  const prefix = type === 'inbound' ? 'IN' : 'OUT';
  const date = new Date().toISOString().slice(0, 10).replace(/-/g, '');
  const random = Math.floor(Math.random() * 1000).toString().padStart(3, '0');
  return `${prefix}${date}${random}`;
}

